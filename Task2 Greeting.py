# 1. Take user's first and last name as input
first_name = input("Enter your first name: ")
last_name = input("Enter your last name: ")

# 2. Concatenate first and last name into a full name
# Added a space between names for readability
full_name = first_name + " " + last_name

# 3. Print a personalized greeting message
print(f"Hello, {full_name}! Welcome to learning python.")

